def examples() -> list[tuple[list[str], dict, str]]:
    """(transcript lines, to-do, "yes"/"no") for each candidate, lines in to_plain's format."""
    out = []
    for k, (lines, cands) in enumerate(S):
        t0 = 600 + 37 * k
        plain = [f"[{(t0 + 9 * i) // 3600:02d}:{(t0 + 9 * i) % 3600 // 60:02d}:{(t0 + 9 * i) % 60:02d}] {who}: {text}"
                 for i, (who, text) in enumerate(lines)]
        for i, todo, answer in cands:
            owner, task = (x.strip() for x in todo.split(":", 1))
            out.append((plain, {"owner": owner, "task": task, "line": i, "quote": lines[i][1]}, answer))
    return out


